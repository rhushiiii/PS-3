"""Report document model shared by the builders and the CSV/XLSX/PDF renderers.

Reports carry aggregates only: no APAAR, names or student ids. A missing value is
``None`` (empty cell, or "No data" in PDF), never zero.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel

ReportKind = Literal[
    "enrolment-summary",
    "intake-utilisation",
    "submission-completeness",
    "resolution-times",
    "validation-findings",
    "open-cases",
    "verification-activity",
]
ReportFormat = Literal["csv", "xlsx", "pdf"]
Cell = str | int | float | bool | None

PROVENANCE = (
    "SIMULATED / DEMO DATA — synthetic records; not an official AICTE report; "
    "simulated verification is not government verification"
)


class ReportTable(BaseModel):
    title: str
    columns: list[str]
    rows: list[list[Cell]]


class ReportDocument(BaseModel):
    kind: ReportKind
    title: str
    generated_at: datetime
    generated_by: str
    filters: dict[str, str]
    academic_year_context: str
    coverage: str
    provenance: str = PROVENANCE
    totals: ReportTable
    data: ReportTable

    def metadata(self) -> list[tuple[str, str]]:
        """Leading metadata rows, in display order (identical in every format)."""
        return [
            ("Report", self.title),
            ("Generated at (UTC)", self.generated_at.isoformat()),
            ("Generated by", self.generated_by),
            (
                "Filters applied",
                "; ".join(f"{k}={v}" for k, v in self.filters.items()) or "none",
            ),
            ("Academic year context", self.academic_year_context),
            ("Coverage", self.coverage),
            ("Provenance", self.provenance),
        ]
